#ifndef __OSW_KEYS_H__
#define __OSW_KEYS_H__

/**
 * Definición de teclas basadas en los keycodes del sistema
 */
#define OSW_KEY_W      17  // para acercarse al modelo (zoom in)
#define OSW_KEY_S      31  // para alejarse del modelo (zoom out)
#define OSW_KEY_ESC    1   // para salir
#define OSW_KEY_L      38  // para alternar luz secundaria
#define OSW_KEY_A      30  // para rotar modelo sobre Y a la izquierda
#define OSW_KEY_D      32  // para rotar modelo sobre Y a la derecha
#define OSW_KEY_R      19  // para alternar rotación automática del modelo
#define OSW_KEY_T      20  // para resetear la rotación manual

#endif /* __OSW_KEYS_H__ */